export async function GET(request: Request) {
  const { searchParams } = new URL(request.url);
  const q = (searchParams.get('q') || '').toLowerCase().trim();
  const category = (searchParams.get('category') || '').toLowerCase().trim();

  let thinkTanks = VERIFIED_THINK_TANKS;
  let sites = DPRK_STRATEGIC_SITES;

  if (category) {
    sites = sites.filter(s => s.category.toLowerCase() === category);
  }

  if (q) {
    thinkTanks = thinkTanks.filter(t => 
      t.name.toLowerCase().includes(q) || 
      t.description.toLowerCase().includes(q) || 
      t.keyFocus.some(f => f.toLowerCase().includes(q))
    );
    sites = sites.filter(s =>
      s.title.toLowerCase().includes(q) ||
      s.source_org.toLowerCase().includes(q) ||
      s.description.toLowerCase().includes(q) ||
      s.category_label.toLowerCase().includes(q) ||
      (s.military_coordinates && s.military_coordinates.mgrs.toLowerCase().includes(q))
    );
  }

  return NextResponse.json({
    status: 'success',
    sites: sites,
    total_sites: sites.length,
    think_tanks: thinkTanks,
    total_think_tanks: thinkTanks.length,
    query: q || 'all',
    timestamp: new Date().toISOString(),
  }, {
    headers: { 'Cache-Control': 'no-store, no-cache, must-revalidate, max-age=0' },
  });
}
