#!/usr/bin/env node
/**
 * Builds public/places.json, the place list OSIRIS looks places up in
 * without asking any outside service (see src/lib/places.ts).
 *
 * From GeoNames (https://www.geonames.org, CC BY 4.0): every town and city of
 * 5,000 people or more, every country and every first-level region. Countries
 * and regions have no point of their own in these files, so each is placed at
 * the middle of its towns, averaged on the sphere so a country across the
 * antimeridian (Fiji, Russia) does not land on the other side of the world.
 *
 * Usage, with the three files from https://download.geonames.org/export/dump/
 * (cities5000.zip unpacked):
 *   node tools/build-places.mjs cities5000.txt countryInfo.txt admin1CodesASCII.txt
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [citiesFile, countriesFile, regionsFile] = process.argv.slice(2);
if (!citiesFile || !countriesFile || !regionsFile) {
  console.error('usage: node tools/build-places.mjs cities5000.txt countryInfo.txt admin1CodesASCII.txt');
  process.exit(1);
}

const rows = (file) => readFileSync(file, 'utf8').split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.split('\t'));

// Sections of a city, and places that no longer exist, are not towns to name.
const SKIP = new Set(['PPLX', 'PPLH', 'PPLQ', 'PPLW', 'PPLCH']);
// Three decimals is about 100 m: plenty for naming a town, and a smaller file.
const round = (n) => Math.round(n * 1e3) / 1e3;

const countries = new Map(rows(countriesFile).map((r) => [r[0], r[4]]));
const regions = new Map(rows(regionsFile).map((r) => [r[0], r[1]]));

const places = [];
for (const r of rows(citiesFile)) {
  if (SKIP.has(r[7])) continue;
  const lat = Number(r[4]);
  const lng = Number(r[5]);
  const pop = Number(r[14]) || 0;
  if (!r[1] || !Number.isFinite(lat) || !Number.isFinite(lng)) continue;
  places.push([r[1], round(lat), round(lng), r[8], r[10] || '', pop, r[7] === 'PPLC' ? 1 : 0]);
}
places.sort((a, b) => b[5] - a[5]);

/** The middle of a set of points, on the sphere. */
function middle(points) {
  let x = 0, y = 0, z = 0;
  for (const [lat, lng] of points) {
    const p = (lat * Math.PI) / 180, l = (lng * Math.PI) / 180;
    x += Math.cos(p) * Math.cos(l);
    y += Math.cos(p) * Math.sin(l);
    z += Math.sin(p);
  }
  const lng = Math.atan2(y, x), lat = Math.atan2(z, Math.hypot(x, y));
  return [round((lat * 180) / Math.PI), round((lng * 180) / Math.PI)];
}

// Countries and regions: the middle of their towns, with their towns' people.
const groups = new Map();
for (const [, lat, lng, cc, a1, pop] of places) {
  for (const key of [cc, a1 ? `${cc}.${a1}` : null]) {
    if (!key) continue;
    const g = groups.get(key) ?? { points: [], pop: 0 };
    g.points.push([lat, lng]);
    g.pop += pop;
    groups.set(key, g);
  }
}
const areas = [];
for (const [key, g] of groups) {
  const [cc, a1] = key.split('.');
  const name = a1 ? regions.get(key) : countries.get(cc);
  if (!name) continue;
  areas.push([name, ...middle(g.points), cc, a1 ?? '', g.pop, a1 ? 'region' : 'country']);
}
areas.sort((a, b) => b[5] - a[5]);

const out = {
  about: 'Towns and cities of 5,000 people or more, every country and its regions, from GeoNames (https://www.geonames.org), CC BY 4.0. Generated by tools/build-places.mjs.',
  countries: Object.fromEntries(countries),
  regions: Object.fromEntries([...regions].filter(([k]) => groups.has(k))),
  /** [name, lat, lng, country code, region code, population, capital], largest first. */
  places,
  /** [name, lat, lng, country code, region code, population, 'country' | 'region'], largest first. */
  areas,
};
writeFileSync(new URL('../public/places.json', import.meta.url), JSON.stringify(out));
console.log(`${places.length} towns, ${areas.filter((a) => a[6] === 'country').length} countries, ${areas.filter((a) => a[6] === 'region').length} regions`);
